export function t(key: string, locale: Locale = DEFAULT_LOCALE): string {
  return translations[locale]?.[key] || translations[DEFAULT_LOCALE]?.[key] || key;
}

/**
 * Get localized value from a Record<string, string> (e.g. name.fr, name.en)
 */
export function localized(obj: Record<string, string> | undefined, locale: Locale = DEFAULT_LOCALE): string {
  if (!obj) return '';
  return obj[locale] || obj[DEFAULT_LOCALE] || Object.values(obj)[0] || '';
}
